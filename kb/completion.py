"""`kb` in any PowerShell window, with Tab completion (`kb completion install`).

- The blueprint folder goes on the user's PATH (no admin), so `kb` works without `.\` from any folder.
- A completion script is written to %LOCALAPPDATA%\\woynich-wiki\\kb-completion.ps1 and dot-sourced from the user's
  PowerShell profile. It is generated from the argparse definition, so new commands and options appear after
  running `kb completion install` again; no Python runs when Tab is pressed.
- Tab shows a menu (PSReadLine MenuComplete) with a one-line description of each command.
"""
from __future__ import annotations

import argparse
import os
import subprocess
import sys
from pathlib import Path

from kb.core import config

BEGIN, END = "# >>> woynich-wiki >>>", "# <<< woynich-wiki <<<"


def tree() -> dict[str, dict]:
    from kb.cli import build_parser
    ap = build_parser()
    subs = next(a for a in ap._actions if isinstance(a, argparse._SubParsersAction))
    helps = {c.dest: c.help or "" for c in subs._choices_actions}
    out = {}
    for name, p in subs.choices.items():
        opts, values = [], []
        for act in p._actions:
            if act.option_strings:
                opts += [o for o in act.option_strings if o.startswith("--") and o != "--help"]
            elif act.choices:
                values += [str(c) for c in act.choices]
        out[name] = {"help": helps.get(name, ""), "opts": opts, "values": values}
    return out


def _q(s: str) -> str:
    return "'" + str(s).replace("'", "''") + "'"


def script() -> str:
    rows = []
    for name, n in sorted(tree().items()):
        arr = lambda xs: "@(" + ",".join(_q(x) for x in xs) + ")"
        rows.append(f"  {_q(name)} = @{{ h = {_q(n['help'])}; o = {arr(n['opts'])}; v = {arr(n['values'])} }}")
    return "\n".join([
        "# woynich-wiki: Tab completion for `kb` (generated by `kb completion install`; run it again after `git pull`).",
        "$global:KbCompletionTree = @{", *rows, "}",
        "$kbComplete = {",
        "    param($wordToComplete, $commandAst, $cursorPosition)",
        "    $tree = $global:KbCompletionTree",
        "    $words = @($commandAst.CommandElements | Select-Object -Skip 1 | ForEach-Object { $_.Extent.Text })",
        "    if ($wordToComplete -and $words.Count -gt 0) { $words = @($words | Select-Object -First ($words.Count - 1)) }",
        "    if ($words.Count -eq 0) {",
        "        $tree.Keys | Sort-Object | Where-Object { $_ -like \"$wordToComplete*\" } | ForEach-Object {",
        "            New-Object System.Management.Automation.CompletionResult($_, $_, 'ParameterValue', $tree[$_].h) }",
        "        return",
        "    }",
        "    $node = $tree[$words[0]]",
        "    if (-not $node) { return }",
        "    if ($wordToComplete.StartsWith('-')) { $cands = @($node.o) }",
        "    elseif ($node.v.Count -eq 0) { return }  # nothing to offer: PowerShell completes file names (kb add <Tab>)",
        "    else { $cands = @($node.v | Where-Object { $words -notcontains $_ }) }",
        "    $cands | Where-Object { $_ -like \"$wordToComplete*\" } | ForEach-Object {",
        "        New-Object System.Management.Automation.CompletionResult($_, $_, 'ParameterValue', $_) }",
        "}",
        "Register-ArgumentCompleter -Native -CommandName kb, kb.cmd -ScriptBlock $kbComplete",
        "if (Get-Module -ListAvailable PSReadLine) { Set-PSReadLineKeyHandler -Key Tab -Function MenuComplete }",
        "",
    ])


def _powershell(cmd: str) -> str:
    r = subprocess.run(["powershell", "-NoProfile", "-NonInteractive", "-Command", cmd], capture_output=True, text=True)
    return r.stdout.strip()


def _add_to_user_path(folder: Path) -> bool:
    """Append `folder` to the user's PATH (HKCU\\Environment, no admin). True if it was added."""
    import ctypes
    import winreg
    with winreg.OpenKey(winreg.HKEY_CURRENT_USER, "Environment", 0, winreg.KEY_READ | winreg.KEY_WRITE) as k:
        try:
            value, kind = winreg.QueryValueEx(k, "Path")
        except FileNotFoundError:
            value, kind = "", winreg.REG_EXPAND_SZ
        parts = [p for p in value.split(";") if p]
        if any(os.path.normcase(p.rstrip("\\")) == os.path.normcase(str(folder)) for p in parts):
            return False
        winreg.SetValueEx(k, "Path", 0, kind, ";".join(parts + [str(folder)]))
    ctypes.windll.user32.SendMessageTimeoutW(0xFFFF, 0x1A, 0, "Environment", 0x2, 5000, None)  # WM_SETTINGCHANGE
    return True


def install() -> str:
    root = config.paths().root
    if sys.platform != "win32":
        return ("Tab completion is set up for Windows PowerShell. On macOS/Linux, add an alias instead:\n"
                f"  alias kb='{root}/.venv/bin/python -m kb'")
    if not (root / "kb.cmd").exists():
        return "kb.cmd not found: run setup.cmd first."
    target = Path(os.environ.get("LOCALAPPDATA", Path.home())) / "woynich-wiki" / "kb-completion.ps1"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(script(), encoding="utf-8-sig")  # BOM: Windows PowerShell 5.1 reads it as UTF-8
    lines = [f"completion script: {target}"]
    lines.append(f"PATH: {'added' if _add_to_user_path(root) else 'already contains'} {root}")
    profile = Path(_powershell("$PROFILE.CurrentUserAllHosts") or Path.home() / "Documents" / "WindowsPowerShell" / "profile.ps1")
    old = profile.read_text(encoding="utf-8-sig") if profile.exists() else ""
    if BEGIN in old and END in old:
        old = old[:old.index(BEGIN)] + old[old.index(END) + len(END):].lstrip("\r\n")
    block = f"{BEGIN}\nif (Test-Path {_q(target)}) {{ . {_q(target)} }}\n{END}\n"
    profile.parent.mkdir(parents=True, exist_ok=True)
    profile.write_text(old.rstrip() + ("\n\n" if old.strip() else "") + block, encoding="utf-8-sig")
    lines.append(f"profile: {profile}")
    policy = _powershell("Get-ExecutionPolicy")
    if policy in ("Restricted", "AllSigned"):
        lines.append(f"\nPowerShell does not run profile scripts here (execution policy {policy}). Allow your own scripts "
                     "for your user only (no admin):\n  Set-ExecutionPolicy -Scope CurrentUser RemoteSigned")
    lines.append("\nOpen a NEW PowerShell window, then type `kb ` and press Tab.")
    return "\n".join(lines)
